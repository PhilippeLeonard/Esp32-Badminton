#!/usr/bin/env python3
"""Turns phone_app.html into app_page.h, a PROGMEM string the sketch serves.

The HTML file stays the single source: edit it, run this, reflash. Keeping a
hand-copied duplicate inside the .ino is how the two drift apart.
"""
import pathlib
import sys

here = pathlib.Path(__file__).parent
html = (here / "phone_app.html").read_text(encoding="utf-8")

# The page goes inside a C++ raw string literal, so the only sequence that
# matters is its terminator.
if ')HTML"' in html:
    sys.exit("the page contains the raw-literal terminator )HTML\" - rename it")

out = (
    "// Generated by make_page.py from phone_app.html - do not edit by hand.\n"
    "#pragma once\n\n"
    'static const char APP_PAGE[] PROGMEM = R"HTML(' + html + ')HTML";\n'
)
(here / "app_page.h").write_text(out, encoding="utf-8")
print(f"app_page.h written, {len(html)} bytes of HTML")
